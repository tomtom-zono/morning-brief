/** 再生成時に付す追加指示(可変部・末尾に置く)。 */
export function retryHint(issues: string[], attempt: number): string {
  return `\n\n【再生成 ${attempt}回目】直前の出力は以下の点で不合格だった。該当箇所を修正して全体を出し直すこと。\n${issues
    .map((s) => ` - ${s}`)
    .join('\n')}`;
}
